// Current Language
let currentLanguage = localStorage.getItem('kboa_language') || 'en';

// Get Translation
function t(key) {
    return translations[currentLanguage][key] || translations['en'][key] || key;
}

// Set Language
function setLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('kboa_language', lang);
    applyTranslations();

    // Toggle RTL for Arabic
    if (lang === 'ar') {
        document.documentElement.setAttribute('dir', 'rtl');
        document.documentElement.setAttribute('lang', 'ar');
    } else {
        document.documentElement.setAttribute('dir', 'ltr');
        document.documentElement.setAttribute('lang', lang);
    }
}

// Apply Translations to DOM
function applyTranslations() {
    // Elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(function(element) {
        const key = element.getAttribute('data-i18n');
        element.textContent = t(key);
    });

    // Elements with data-i18n-placeholder (for inputs)
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function(element) {
        const key = element.getAttribute('data-i18n-placeholder');
        element.placeholder = t(key);
    });

    // Update language switcher UI
    updateLanguageSwitcher();
}

// Update Language Switcher
function updateLanguageSwitcher() {
    document.querySelectorAll('.lang-option').forEach(function(btn) {
        btn.classList.toggle('active', btn.getAttribute('data-lang') === currentLanguage);
    });
}

// Create Language Switcher HTML
function createLanguageSwitcher() {
    return `
        <div class="language-switcher" style="display: flex; gap: 8px; align-items: center;">
            <button class="lang-option ${currentLanguage === 'en' ? 'active' : ''}" 
                    data-lang="en" onclick="setLanguage('en')"
                    style="padding: 6px 12px; border-radius: 6px; border: 1px solid var(--gray-300); background: ${currentLanguage === 'en' ? 'var(--primary-color)' : 'white'}; color: ${currentLanguage === 'en' ? 'white' : 'var(--gray-600)'}; font-weight: 600; cursor: pointer; font-size: 0.85rem;">
                EN
            </button>
            <button class="lang-option ${currentLanguage === 'ha' ? 'active' : ''}" 
                    data-lang="ha" onclick="setLanguage('ha')"
                    style="padding: 6px 12px; border-radius: 6px; border: 1px solid var(--gray-300); background: ${currentLanguage === 'ha' ? 'var(--primary-color)' : 'white'}; color: ${currentLanguage === 'ha' ? 'white' : 'var(--gray-600)'}; font-weight: 600; cursor: pointer; font-size: 0.85rem;">
                HA
            </button>
            <button class="lang-option ${currentLanguage === 'ar' ? 'active' : ''}" 
                    data-lang="ar" onclick="setLanguage('ar')"
                    style="padding: 6px 12px; border-radius: 6px; border: 1px solid var(--gray-300); background: ${currentLanguage === 'ar' ? 'var(--primary-color)' : 'white'}; color: ${currentLanguage === 'ar' ? 'white' : 'var(--gray-600)'}; font-weight: 600; cursor: pointer; font-size: 0.85rem;">
                عربي
            </button>
        </div>
    `;
}

// Initialize on page load
document.addEventListener('DOMContentLoaded', function() {
    applyTranslations();

    // Inject language switcher into header if placeholder exists
    const switcherContainer = document.getElementById('language-switcher');
    if (switcherContainer) {
        switcherContainer.innerHTML = createLanguageSwitcher();
    }
});

// Make functions global
window.t = t;
window.setLanguage = setLanguage;
window.createLanguageSwitcher = createLanguageSwitcher;
